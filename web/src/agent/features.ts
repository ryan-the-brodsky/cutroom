/** The shot the human is looking at, so `:sid` routes can resolve themselves. */
function currentSid(ctx: ActionContext): string | null {
  try {
    const cur = ctx.page.current();
    if (cur?.kind === "shot") return cur.sid;
    if (cur?.kind === "film") return cur.getState().selected ?? null;
  } catch { /* no handles yet */ }
  return null;
}

/**
 * Navigate to where a feature lives and pulse its control. This is the one
 * execution path every palette-only entry shares: `trail.step` does the pulse,
 * so the human sees the same ring the tools draw.
 */
export async function walkTo(ctx: ActionContext, def: ActionDef, where: Where): Promise<ToolResult> {
  let route = where.route;
  if (route.includes(":pid")) {
    if (!ctx.project) {
      return err("no_project", { hint: "Open a project first, then ask again." });
    }
    route = route.replace(":pid", ctx.project);
  }
  if (route.includes(":sid")) {
    const sid = currentSid(ctx);
    if (!sid) {
      return err("needs_shot", {
        where: where.label,
        hint: `"${def.title}" lives inside the Shot Editor — open a shot first (open_shot), then ask again.`,
      });
    }
    route = route.replace(":sid", sid);
  }
  const params = new URLSearchParams();
  for (const [k, v] of Object.entries(where.query || {})) if (v) params.set(k, v);
  const url = `${route}${params.toString() ? `?${params}` : ""}`;

  try { await ctx.nav(url); }
  catch (e) {
    return err("nav_failed", { hint: `Could not open ${url}: ${(e as Error)?.message ?? ""}`.trim() });
  }
  await ctx.trail.step({
    tool: def.name, title: `Here: ${where.label}`,
    anchor: where.anchor, detail: def.howTo,
  });
  return ok(def.howTo || `${def.title} — ${where.label}`, {
    feature: def.name, title: def.title, where: where.label, route: url,
    how_to: def.howTo,
  });
}

interface Spec {
  name: string;
  title: string;
  /** One sentence, ≤200 chars: what this control does. */
  description: string;
  group: string;
  route: string;
  query?: Record<string, string>;
  anchor?: string;
  label: string;
  keywords: string[];
  howTo: string;
}

/** Palette-only ActionDef from a compact row. */
function feature(spec: Spec): ActionDef {
  const where: Where = {
    route: spec.route, query: spec.query, anchor: spec.anchor, label: spec.label,
  };
  const def: ActionDef = {
    name: spec.name,
    title: spec.title,
    description: spec.description,
    inputSchema: { type: "object", properties: {}, additionalProperties: false },
    annotations: { readOnlyHint: true },
    where,
    keywords: spec.keywords,
    howTo: spec.howTo,
    group: spec.group,
    surfaces: { agent: false, palette: true },
    summarize: () => `Show me ${spec.title}`,
    execute: (_a, ctx) => walkTo(ctx, def, where),
  };
  return def;
}

