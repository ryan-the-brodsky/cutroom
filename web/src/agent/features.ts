/**
 * The feature registry — every user-facing action in Genga Studio that is NOT a tool.
 *
 * A tool executes. A feature *teaches*: it navigates to where the control lives,
 * pulses it, and hands back the sentence a human would follow. Together with the
 * tool catalogue this is the whole application, one entry per thing you can do,
 * which is what makes the ⌘K palette and `show_me` complete rather than a curated
 * highlight reel. Registry entries here are palette-only (`surfaces.agent:false`),
 * so they do not spend the agent's tool budget — `list_features` and `show_me`
 * still reach them.
 *
 * Owned by workstream I. See docs/WEBMCP-PLAN.md §4 "Feature registry".
 */
